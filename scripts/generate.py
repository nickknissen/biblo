"""Regenerate everything derived from other files. Run after changing the spec or src/biblo/_async.

    uv run python scripts/generate.py           # write
    uv run python scripts/generate.py --check   # fail if anything is out of date (CI)
    uv run python scripts/generate.py --fetch   # first download the live OpenAPI spec

Generates:
- src/biblo/models/_generated.py   Pydantic models from spec/ddf-openapi.json (datamodel-codegen,
                                   configured in pyproject.toml), with the spec's string
                                   patterns, lengths and bounds removed: they describe what the
                                   server sends today, and enforcing them would turn a harmless
                                   server change into a crash for every installed release.
- src/biblo/_app_types.py          Which endpoints need an `x-app-type` other than "biblo".
- src/biblo/_sync/                 The sync client, from src/biblo/_async/ (unasync).
"""

from __future__ import annotations

import argparse
import ast
import json
import re
import shutil
import subprocess
import sys
import tempfile
import urllib.request
from collections.abc import Iterator
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "spec" / "ddf-openapi.json"
PATCHES = ROOT / "spec" / "patches.json"
SPEC_URL = "https://api.detdigitalefolkebibliotek.dk/_openapi.json"
PKG = ROOT / "src" / "biblo"
MODELS = PKG / "models" / "_generated.py"
APP_TYPES = PKG / "_app_types.py"
ASYNC_DIR = PKG / "_async"
SYNC_DIR = PKG / "_sync"

DROPPED_FIELD_KEYWORDS = {
    "pattern",
    "min_length",
    "max_length",
    "ge",
    "le",
    "gt",
    "lt",
    "multiple_of",
    "examples",
}
HEADER = "# Generated by scripts/generate.py from spec/ddf-openapi.json. Do not edit.\n"
PREFERRED_APP_TYPE = "biblo"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    parser.add_argument("--fetch", action="store_true", help="download the live spec first")
    args = parser.parse_args()

    if args.fetch:
        fetch_spec()

    outputs = {
        MODELS: generate_models(),
        APP_TYPES: generate_app_types(),
        **generate_sync(),
    }
    outputs = format_python(outputs)

    stale = [p for p, text in outputs.items() if not p.exists() or p.read_text() != text]
    expected_sync = {p for p in outputs if p.is_relative_to(SYNC_DIR)}
    orphans = (
        [p for p in SYNC_DIR.rglob("*.py") if p not in expected_sync] if SYNC_DIR.exists() else []
    )

    if args.check:
        for path in [*stale, *orphans]:
            print(f"out of date: {path.relative_to(ROOT)}")
        if stale or orphans:
            print("Run: uv run python scripts/generate.py")
            return 1
        return 0

    for path in orphans:
        path.unlink()
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    print(f"wrote {len(outputs)} files")
    return 0


def fetch_spec() -> None:
    with urllib.request.urlopen(SPEC_URL, timeout=30) as response:
        spec = json.load(response)
    SPEC.write_text(json.dumps(spec, indent=2, ensure_ascii=False) + "\n")
    print(f"fetched {SPEC_URL} ({spec['info'].get('description', '')})")


# --------------------------------------------------------------------------- models


def generate_models() -> str:
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "models.py"
        subprocess.run(
            ["datamodel-codegen", "--output", str(out), "--formatters", "builtin"],
            cwd=ROOT,
            check=True,
            capture_output=True,
        )
        source = out.read_text()
    source = re.sub(r"\A# generated by datamodel-codegen:\n(#.*\n)*", "", source)
    source = loosen_constraints(source)
    source = apply_patches(source, json.loads(PATCHES.read_text()))
    source = add_lenient(source)
    tree = ast.parse(source)
    names = sorted(n.name for n in tree.body if isinstance(n, ast.ClassDef))
    exports = "\n\n__all__ = [\n" + "".join(f'    "{n}",\n' for n in names) + "]\n"
    return HEADER + source + exports


class _Source:
    """Source text with AST node spans, for edits that keep the rest byte for byte."""

    def __init__(self, source: str) -> None:
        self.source = source
        self.tree = ast.parse(source)
        self._starts = [0]
        for line in source.splitlines(keepends=True):
            self._starts.append(self._starts[-1] + len(line))

    def span(self, node: ast.AST) -> tuple[int, int]:
        n: Any = node
        return (
            self._starts[n.lineno - 1] + n.col_offset,
            self._starts[n.end_lineno - 1] + n.end_col_offset,
        )

    def text(self, node: ast.AST) -> str:
        start, end = self.span(node)
        return self.source[start:end]

    def fields(self) -> Iterator[tuple[ast.ClassDef, ast.AnnAssign]]:
        for cls in self.tree.body:
            if isinstance(cls, ast.ClassDef):
                for item in cls.body:
                    if isinstance(item, ast.AnnAssign) and isinstance(item.target, ast.Name):
                        yield cls, item

    def replaced(self, replacements: list[tuple[int, int, str]]) -> str:
        """Apply non-overlapping replacements; where they nest, only the outermost."""
        changes = sorted(r for r in replacements if self.source[r[0] : r[1]] != r[2])
        outer: list[tuple[int, int, str]] = []
        for start, end, new in changes:
            if not outer or start >= outer[-1][1]:
                outer.append((start, end, new))
        result = self.source
        for start, end, new in reversed(outer):
            result = result[:start] + new + result[end:]
        return result


def _annotated_parts(src: _Source, annotation: ast.expr) -> tuple[ast.expr, list[str]]:
    """(type, metadata texts) of `Annotated[type, *metadata]`, or (annotation, [])."""
    if (
        isinstance(annotation, ast.Subscript)
        and isinstance(annotation.value, ast.Name)
        and annotation.value.id == "Annotated"
        and isinstance(annotation.slice, ast.Tuple)
    ):
        base, *metadata = annotation.slice.elts
        return base, [src.text(m) for m in metadata]
    return annotation, []


def apply_patches(source: str, patches: dict[str, dict[str, Any]]) -> str:
    """Make the fields spec/patches.json names nullable and optional.

    A patch is `"Model.field": {"nullable": true, "reason": "..."}`, with the generated
    class and Python field name: where the live API contradicts the spec.
    """
    src = _Source(source)
    found: set[str] = set()
    replacements = []
    for cls, item in src.fields():
        key = f"{cls.name}.{item.target.id}"  # type: ignore[union-attr]
        if not patches.get(key, {}).get("nullable"):
            continue
        found.add(key)
        base, metadata = _annotated_parts(src, item.annotation)
        base_text = src.text(base)
        if not re.search(r"\bNone\b", base_text):
            base_text = f"{base_text} | None"
        annotation = f"Annotated[{', '.join([base_text, *metadata])}]" if metadata else base_text
        value = f" = {src.text(item.value)}" if item.value is not None else " = None"
        replacements.append((*src.span(item), f"{item.target.id}: {annotation}{value}"))  # type: ignore[union-attr]
    if missing := set(patches) - found:
        raise SystemExit(f"spec/patches.json names fields that don't exist: {sorted(missing)}")
    return src.replaced(replacements)


def _is_single_literal(node: ast.expr) -> bool:
    return (
        isinstance(node, ast.Subscript)
        and isinstance(node.value, ast.Name)
        and node.value.id == "Literal"
        and not isinstance(node.slice, ast.Tuple)
    )


def add_lenient(source: str) -> str:
    """Give every field the Lenient validator (see biblo/models/_lenient.py)."""
    src = _Source(source)
    replacements = []
    for _, item in src.fields():
        if item.target.id == "model_config":  # type: ignore[union-attr]
            continue
        base, metadata = _annotated_parts(src, item.annotation)
        if _is_single_literal(base):  # a union's discriminator: must match, and pydantic
            continue  # allows no wrap validator on it
        parts = [src.text(base), *metadata, "Lenient"]
        replacements.append((*src.span(item.annotation), f"Annotated[{', '.join(parts)}]"))
    result = src.replaced(replacements)
    imports_end = re.search(r"^from pydantic import .*?$", result, re.M | re.S)
    assert imports_end is not None
    head, tail = result[: imports_end.end()], result[imports_end.end() :]
    return f"{head}\n\nfrom ._lenient import Lenient{tail}"


def loosen_constraints(source: str) -> str:
    """Drop validation keywords from Field(...) and unwrap Annotated[X, Field()] to X.

    Edits source spans rather than re-printing the AST, so docstrings and layout survive.
    """
    src = _Source(source)
    tree, span, text = src.tree, src.span, src.text

    def is_field(node: ast.AST) -> bool:
        return (
            isinstance(node, ast.Call)
            and isinstance(node.func, ast.Name)
            and node.func.id == "Field"
        )

    def field_without_constraints(call: ast.Call) -> str | None:
        """The call's new text, or None when nothing is left of it."""
        kept = [text(a) for a in call.args]
        kept += [text(k) for k in call.keywords if k.arg not in DROPPED_FIELD_KEYWORDS]
        return f"Field({', '.join(kept)})" if kept else None

    replacements: list[tuple[int, int, str]] = []
    handled: set[int] = set()
    for node in ast.walk(tree):
        if (
            isinstance(node, ast.Subscript)
            and isinstance(node.value, ast.Name)
            and node.value.id == "Annotated"
            and isinstance(node.slice, ast.Tuple)
        ):
            base, *metadata = node.slice.elts
            new_metadata = []
            for item in metadata:
                if is_field(item):
                    handled.add(id(item))
                    if (new := field_without_constraints(item)) is not None:  # type: ignore[arg-type]
                        new_metadata.append(new)
                else:
                    new_metadata.append(text(item))
            new_text = text(base)
            if new_metadata:
                new_text = f"Annotated[{', '.join([new_text, *new_metadata])}]"
            replacements.append((*span(node), new_text))
    for node in ast.walk(tree):
        if is_field(node) and id(node) not in handled:
            new = field_without_constraints(node) or "Field()"  # type: ignore[arg-type]
            replacements.append((*span(node), new))

    # Annotated[...] can nest (list[Annotated[...]] inside Annotated[...]); the outer
    # replacement was rebuilt from untouched inner source, so repeat until nothing changes.
    result = src.replaced(replacements)
    return result if result == source else loosen_constraints(result)


# ------------------------------------------------------------------------ app types


def generate_app_types() -> str:
    spec = json.loads(SPEC.read_text())
    schemas = spec["components"]["schemas"]
    overrides: dict[tuple[str, str], str] = {}
    for path, operations in spec["paths"].items():
        for method, operation in operations.items():
            if not isinstance(operation, dict) or method == "head":
                continue
            header = next(
                (
                    p
                    for p in operation.get("parameters", [])
                    if p.get("in") == "header" and p.get("name", "").lower() == "x-app-type"
                ),
                None,
            )
            if header is None:
                continue  # webhooks for DDF's partners, not app endpoints
            schema = header["schema"]
            if "$ref" in schema:
                schema = schemas[schema["$ref"].rsplit("/", 1)[-1]]
            allowed: list[str] = schema["enum"]
            if PREFERRED_APP_TYPE not in allowed:
                overrides[(method.upper(), path)] = allowed[0]

    lines = [
        HEADER,
        '"""The `x-app-type` for endpoints that refuse "biblo". The API serves three apps:',
        "Biblo (digital loans), Mit Biblo (the physical library: branches, events, Scan & Loan)",
        'and Biblo Go (children). Every endpoint not listed here accepts "biblo"."""',
        "",
        f'DEFAULT_APP_TYPE = "{PREFERRED_APP_TYPE}"',
        "",
        "APP_TYPE_OVERRIDES: dict[tuple[str, str], str] = {",
        *(f"    {key!r}: {value!r}," for key, value in sorted(overrides.items())),
        "}",
    ]
    return "\n".join(lines) + "\n"


# ----------------------------------------------------------------------------- sync


def generate_sync() -> dict[Path, str]:
    import unasync

    sources = sorted(ASYNC_DIR.rglob("*.py"))
    names = set()
    for source in sources:
        names |= set(re.findall(r"\bAsync([A-Z]\w*)", source.read_text()))
    replacements = {f"Async{name}": name for name in names}
    replacements |= {
        "_async": "_sync",
        "AsyncClient": "Client",
        "aclose": "close",
        "asyncio": "threading",  # asyncio.Lock -> threading.Lock
        "aiter": "iter",
        "anext": "next",
    }

    outputs: dict[Path, str] = {}
    with tempfile.TemporaryDirectory() as tmp:
        tmp_async = Path(tmp) / "_async"
        tmp_sync = Path(tmp) / "_sync"
        shutil.copytree(ASYNC_DIR, tmp_async)
        rule = unasync.Rule(str(tmp_async), str(tmp_sync), additional_replacements=replacements)
        unasync.unasync_files([str(p) for p in tmp_async.rglob("*.py")], rules=[rule])
        for generated in sorted(tmp_sync.rglob("*.py")):
            relative = generated.relative_to(tmp_sync)
            text = generated.read_text()
            header = "# Generated from src/biblo/_async by scripts/generate.py. Do not edit.\n"
            outputs[SYNC_DIR / relative] = header + text
    return outputs


# ----------------------------------------------------------------------- formatting


def format_python(outputs: dict[Path, str]) -> dict[Path, str]:
    """ruff --fix and ruff format, in a temp dir so --check doesn't touch the tree."""
    formatted: dict[Path, str] = {}
    with tempfile.TemporaryDirectory(dir=ROOT) as tmp:
        tmp_root = Path(tmp)
        mapping = {}
        for i, (path, text) in enumerate(outputs.items()):
            tmp_path = tmp_root / f"f{i}" / path.name
            tmp_path.parent.mkdir()
            tmp_path.write_text(text)
            mapping[path] = tmp_path
        files = [str(p) for p in mapping.values()]
        subprocess.run(
            ["ruff", "check", "--fix", "--exit-zero", *files],
            cwd=ROOT,
            check=True,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
        subprocess.run(["ruff", "format", "--quiet", *files], cwd=ROOT, check=True)
        for path, tmp_path in mapping.items():
            formatted[path] = tmp_path.read_text()
    return formatted


if __name__ == "__main__":
    sys.exit(main())
